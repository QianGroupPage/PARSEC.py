@dataclass(frozen=True)
class PointGroupReduction(SignedPermutationReduction):
    """Orbits of a subgroup ``H`` of the full point group ``G`` whose orbitals use only the 1-D sectors of ``H``.

    ``operations`` are the signed permutations of ``H``; ``full_operations`` those of ``G``;
    ``sector_characters[s, h]`` the real one-dimensional character of solved sector ``s`` at operation ``h``
    of ``H``; ``sector_weights[s]`` how many states each state of sector ``s`` counts for (its degeneracy in
    ``G`` over the number of solved sectors that hold the level, :mod:`.orbital_groups`); ``coset_images[c,
    w]`` the orbit of ``c r_w`` for the right coset representatives ``c`` of ``G`` (``G`` = union of ``H c``,
    the identity first), which average an ``H``-invariant field over ``G``:

    ``f_G(w) = (1 / [G:H]) sum_c f[coset_images[c, w]]``.

    The scalar fields (density, potentials) keep one value per orbit of ``H`` as before.  ``generator_bits``
    is empty: ``H`` need not be abelian or of order two per element.
    """

    full_operations: np.ndarray = None
    sector_characters: np.ndarray = None
    sector_weights: np.ndarray = None
    coset_images: np.ndarray = None
    # the right coset representatives as matrices (the identity first) and the grid, which give the partner
    # states of a weighted one (:meth:`partner_states`)
    coset_operations: np.ndarray = None
    grid: object = field(default=None, compare=False, repr=False)
    # The translations (grid steps) that follow ``operations``, ``full_operations`` and ``coset_operations``
    # (``r -> R r + t``) in a cell that repeats a smaller one; ``None``: none (the point group about the origin).
    translations: np.ndarray = None
    full_translations: np.ndarray = None
    coset_translations: np.ndarray = None
    # The orbits of the atoms under ``operations`` (with their translations): the smallest atom index of the
    # orbit of every atom and the orbit size (:func:`_atom_orbits`; ``None``: not known).  Atoms of one orbit
    # give the same nonlocal operator in every sector (:func:`compress_projectors_for_sectors`).
    atom_representatives: np.ndarray = None
    atom_orbit_sizes: np.ndarray = None

    def operation_translation(self, index: int) -> np.ndarray | None:
        """The translation of ``operations[index]`` (grid steps), ``None`` without translations."""

        return None if self.translations is None else np.asarray(self.translations[index], dtype=np.int64)

    @property
    def coset_count(self) -> int:
        return int(self.coset_images.shape[0])

    def partner_states(self, vectors: np.ndarray, weights: np.ndarray) -> np.ndarray:
        """Full-grid states with the partners of every weighted one: ``sum(weights)`` columns.

        ``vectors`` (full grid x states) are solved sector states; a state of weight ``w > 1`` stands for
        ``w`` degenerate partners, which lie in the span of its images ``psi(g^-1 r)`` under the operations
        ``g`` of the full group (one per left coset ``g H`` suffices: ``psi`` is an eigenfunction of every
        operation of ``H``).  The images are orthonormalized after the state itself, which stays the first
        partner, in the order of the operations, until ``w`` independent ones are found; the row map of an
        operation is built once.  A state of weight 1 is copied.
        """

        vectors = np.asarray(vectors, dtype=np.float64)
        weights = np.asarray(weights, dtype=np.int64)
        if vectors.ndim != 2 or vectors.shape[1] != weights.size:
            raise ValueError("one weight per state is needed")
        if np.all(weights == 1):
            return vectors.copy()
        if self.grid is None or self.full_operations is None:
            raise RuntimeError("the partner states need the grid and the operations of the full group")
        identity = np.eye(3, dtype=np.int8)
        full = np.asarray(self.full_operations, dtype=np.int8)
        shifts = (
            np.zeros((full.shape[0], 3), dtype=np.int64)
            if self.full_translations is None
            else np.asarray(self.full_translations, dtype=np.int64)
        )
        kept = [
            index for index in range(full.shape[0])
            if not (np.array_equal(full[index], identity) and not np.any(shifts[index]))
        ]
        operations = [full[index] for index in kept]
        operation_shifts = [shifts[index] for index in kept]
        cache: dict[int, np.ndarray] = {}

        def row_map(index: int) -> np.ndarray:
            if index not in cache:
                mapping = _grid_row_mapping_operation(
                    self.grid, operations[index], 1.0e-10, translation=operation_shifts[index]
                )
                if mapping is None:
                    raise RuntimeError("an operation of the full group no longer maps the grid")
                cache[index] = mapping
            return cache[index]

        out = np.empty((vectors.shape[0], int(weights.sum())), dtype=np.float64)
        column = 0
        for index, weight in enumerate(weights):
            state = vectors[:, index]
            out[:, column] = state
            if weight == 1:
                column += 1
                continue
            kept = [state / np.linalg.norm(state)]
            for operation in range(len(operations)):
                if len(kept) == weight:
                    break
                image = np.empty_like(state)
                image[row_map(operation)] = state
                for basis in kept:
                    image -= np.dot(basis, image) * basis
                norm = np.linalg.norm(image)
                if norm > 1.0e-6 * np.linalg.norm(state):
                    kept.append(image / norm)
            if len(kept) != weight:
                raise RuntimeError("the images of a weighted state give too few partners")
            scale = np.linalg.norm(state)
            for offset, basis in enumerate(kept[1:], start=1):
                out[:, column + offset] = basis * scale
            column += int(weight)
        return out

    def symmetrize_values(self, values: np.ndarray) -> np.ndarray:
        """The average over ``G`` of an ``H``-invariant field given by its orbit values."""

        values = np.asarray(values, dtype=np.float64)
        if self.coset_count <= 1:
            return values.copy()
        total = values[self.coset_images[0]].copy()
        for images in self.coset_images[1:]:
            total += values[images]
        return total / float(self.coset_count)


def _point_group_operations(
    grid: RealSpaceGrid,
    atoms: Sequence[Atom],
    atom_tolerance: float,
    lattice_tolerance: float,
    table,
) -> list[np.ndarray]:
    """The signed permutations that map the atoms onto themselves and the lattice onto itself (the identity first).

    Whether one maps the active grid onto itself is decided by its row map, which is built for the operations
    of the chosen subgroup and the coset representatives only (every other one is a product of those).
    """

    species = _positions_by_species(atoms)
    period = _lattice_period(grid)
    identity = np.eye(3, dtype=np.int8)
    found = [identity]
    for operation in _signed_permutation_operations():
        if np.array_equal(operation, identity):
            continue
        if not _atoms_are_invariant_operation(species, operation, atom_tolerance, period):
            continue
        if _integer_signed_permutation_parameters(grid, operation, lattice_tolerance) is None:
            continue
        found.append(operation)
    return found


_TRANSLATIONS_SWITCH = "PARSEC_PERIODIC_TRANSLATIONS"


def periodic_translation_setting() -> str:
    """``PARSEC_PERIODIC_TRANSLATIONS``: ``auto`` (default) adds the half-cell translations of a cell that repeats
    a smaller one to its group (:func:`_half_cell_translations`) and, where the group closes, the operations whose
    translation is a fraction of the cell (non-symmorphic, :func:`_fractional_translation`); ``half`` the half-cell
    translations alone; ``off`` keeps the point group about the origin alone, bit for bit as before."""

    value = os.environ.get(_TRANSLATIONS_SWITCH, "auto").strip().lower() or "auto"
    if value not in {"auto", "half", "off"}:
        raise ValueError(f"{_TRANSLATIONS_SWITCH} must be auto, half or off, not {value!r}")
    return value


def _half_cell_translations(
    grid: RealSpaceGrid, species: dict, atom_tolerance: float, trees: dict | None = None
) -> list[np.ndarray]:
    """The translations by half the cell along a set of its axes that map the atoms onto themselves (grid steps).

    A cell that repeats a smaller one twice along an axis is invariant under the translation by half of that
    axis; the grid maps onto itself where the axis has an even number of points.  These translations form a
    group of order two per element (the time-reversal-invariant k-points of the smaller cell are its real
    characters).  Only a bulk orthorhombic cell whose rows are its box takes them; the zero translation first.
    """

    zero = np.zeros(3, dtype=np.int64)
    period = _lattice_period(grid)
    if period is None or not _periodic_row_major(grid) or periodic_translation_setting() == "off":
        return [zero]
    counts = np.asarray(grid.points_per_axis, dtype=np.int64)
    found = [zero]
    for bits in product((0, 1), repeat=3):
        bits = np.asarray(bits, dtype=np.int64)
        if not np.any(bits) or np.any((bits == 1) & (counts % 2 == 1)):
            continue
        steps = bits * (counts // 2)
        shift = bits * period / 2.0
        if _plausible(species, {} if trees is None else trees, np.eye(3), shift, atom_tolerance, period) and all(
            _has_tolerance_perfect_matching(positions + shift, positions, atom_tolerance, period)
            for positions in species.values()
        ):
            found.append(steps)
    return found


_SAMPLE_ATOMS = 64


def _plausible(species: dict, trees: dict, operation, translation, tolerance: float, period) -> bool:
    """Whether the first atoms of every species land near an atom of it under ``r -> R r + t`` (bohr).

    A necessary condition of :func:`_atoms_are_invariant_operation`, from one k-d tree query of a few atoms: the
    candidates it refuses are refused there too, so the group found is the same; it spares the full matching
    of a large cell for the operations that fail.  ``trees`` (the caller's) keeps the k-d tree of each species.
    """

    from scipy.spatial import cKDTree

    radius = 2.0 * (tolerance * (1.0 + 1.0e-9) + 1.0e-12)
    matrix = np.asarray(operation, dtype=np.float64)
    for symbol, positions in species.items():
        tree = trees.get(symbol)
        if tree is None:
            tree = trees[symbol] = _matching_tree(positions, period)
        sample = positions[:_SAMPLE_ATOMS] @ matrix.T
        if translation is not None:
            sample = sample + np.asarray(translation, dtype=np.float64)
        queries = sample if period is None else _folded(sample, period)
        distances, _ = tree.query(queries, k=1, distance_upper_bound=radius)
        if not np.all(np.isfinite(distances)):
            return False
    return True



_FRACTIONAL_SAMPLES = 8
# Candidates matched in full at most: more of them after the sampled atoms (a crystal of many cells, whose lattice
# translations all pass, or one whose translations a defect alone breaks) end the search as undecided.
_FRACTIONAL_BUDGET = 32
_UNDECIDED = "undecided"


def _translations_mapping(species: dict, trees: dict, operation, period, steps, counts, tolerance,
                          excluded=(), first: bool = True):
    """The translations ``t`` (whole grid steps, ascending) with which ``r -> R r + t`` maps the atoms onto
    themselves, apart from ``excluded``.

    A valid ``t`` carries the first atom of the smallest species onto an atom of that species, so the candidates
    are ``x_j - R x_0``; those that are whole grid steps are kept, then those that carry the next few atoms of
    every species onto atoms of it (one k-d tree query of all candidates per atom), and the survivors are
    matched in full (:func:`_atoms_are_invariant_operation`); with ``first`` (the default) the search stops at the
    first one, which is all the callers need (whether one exists, and one of a coset).  More than
    ``_FRACTIONAL_BUDGET`` candidates after the sampled atoms return ``_UNDECIDED``.
    """

    matrix = np.asarray(operation, dtype=np.float64)
    symbol = min(species, key=lambda name: (len(species[name]), name))
    positions = species[symbol]
    candidates = positions - positions[0] @ matrix.T
    candidates = candidates - period * np.floor(candidates / period)
    in_steps = candidates / steps
    rounded = np.rint(in_steps)
    keep = np.all(np.abs(in_steps - rounded) <= 1.0e-6, axis=1)
    whole = np.unique(np.mod(rounded[keep].astype(np.int64), counts), axis=0)
    if excluded:
        drop = {tuple(int(v) for v in np.mod(np.asarray(step, dtype=np.int64), counts)) for step in excluded}
        whole = np.array([row for row in whole if tuple(int(v) for v in row) not in drop], dtype=np.int64).reshape(-1, 3)
    radius = 2.0 * (tolerance * (1.0 + 1.0e-9) + 1.0e-12)
    for name, atoms_of in species.items():
        if whole.size == 0:
            return []
        tree = trees.get(name)
        if tree is None:
            tree = trees[name] = _matching_tree(atoms_of, period)
        # atoms spread over the list (the first one of the smallest species made the candidates)
        picks = np.unique(np.linspace(1 if name == symbol else 0, len(atoms_of) - 1, _FRACTIONAL_SAMPLES).astype(int))
        for atom in atoms_of[picks] if picks.size and picks[-1] >= picks[0] else atoms_of[:0]:
            images = atom @ matrix.T + whole * steps
            distances, _ = tree.query(_folded(images, period), k=1, distance_upper_bound=radius)
            whole = whole[np.isfinite(distances)]
            if whole.size == 0:
                return []
    if whole.shape[0] > _FRACTIONAL_BUDGET:
        return _UNDECIDED
    valid = []
    for row in whole:
        if _atoms_are_invariant_operation(species, operation, tolerance, period, row * steps):
            valid.append(row)
            if first:
                break
    return valid


def _fractional_translation(species, trees, operation, period, steps, counts, tolerance):
    """One translation (grid steps) that makes ``r -> R r + t`` a symmetry of the atoms, or ``None``."""

    found = _translations_mapping(species, trees, operation, period, steps, counts, tolerance)
    return found[0] if found and found is not _UNDECIDED else None


def _space_group_operations(grid, atoms, atom_tolerance, lattice_tolerance, *, fractional: bool = True):
    """``(matrices, translations)`` of the operations ``r -> R r + t`` of a periodic cell, the identity first.

    ``R`` a signed permutation that maps the lattice of the grid onto itself, ``t`` one of the half-cell
    translations ``T`` of :func:`_half_cell_translations`.  The ``t`` that go with one ``R`` form a coset of
    ``T``: one is searched (the zero first), the others follow.  With ``T`` the zero translation alone these are
    the operations of :func:`_point_group_operations`, in its order.
    """

    species = _positions_by_species(atoms)
    period = _lattice_period(grid)
    trees: dict = {}
    translations = _half_cell_translations(grid, species, atom_tolerance, trees)
    counts = np.asarray(grid.points_per_axis, dtype=np.int64)
    steps = np.diag(np.asarray(grid.cell.lattice_vectors, dtype=np.float64)) / counts if len(translations) > 1 else None
    identity = np.eye(3, dtype=np.int8)
    matrices = [identity]
    shifts = [translations[0]]
    for translation in translations[1:]:
        matrices.append(identity)
        shifts.append(translation)
    # Operations with a fraction of the cell as translation (non-symmorphic) close into a group with the
    # half-cell translations only where these are all the pure translations of the crystal modulo the cell; a
    # crystal with more (a supercell of n > 1 cubes of diamond) would need all of them, of complex characters.
    fractional = (
        fractional
        and periodic_translation_setting() == "auto"
        and period is not None
        # no pure translation besides the half-cell ones (undecided counts as some)
        and _translations_mapping(
            species, trees, identity, period, np.diag(np.asarray(grid.cell.lattice_vectors, dtype=np.float64)) / counts,
            counts, atom_tolerance, excluded=translations,
        ) == []
    )
    if fractional and steps is None:
        steps = np.diag(np.asarray(grid.cell.lattice_vectors, dtype=np.float64)) / counts
    for operation in _signed_permutation_operations():
        if np.array_equal(operation, identity):
            continue
        if _integer_signed_permutation_parameters(grid, operation, lattice_tolerance) is None:
            continue
        found = None
        for candidate in ([translations[0]] if len(translations) == 1 else _all_half_cell_steps(counts)):
            cartesian = None if len(translations) == 1 else candidate * steps
            if _plausible(species, trees, operation, cartesian, atom_tolerance, period) and _atoms_are_invariant_operation(
                species, operation, atom_tolerance, period, cartesian
            ):
                found = candidate
                break
        if found is None and fractional:
            found = _fractional_translation(species, trees, operation, period, steps, counts, atom_tolerance)
        if found is None:
            continue
        for translation in translations:
            matrices.append(operation)
            shifts.append((found + translation) % counts)
    return matrices, shifts


def _affine_matrix(operation: np.ndarray, translation: np.ndarray) -> np.ndarray:
    """``[[R, t], [0, 1]]`` (``t`` in grid steps): the element of the group table of ``r -> R r + t``."""

    matrix = np.eye(4, dtype=np.int64)
    matrix[:3, :3] = np.asarray(operation, dtype=np.int64)
    matrix[:3, 3] = np.asarray(translation, dtype=np.int64)
    return matrix


def _all_half_cell_steps(counts: np.ndarray) -> list[np.ndarray]:
    """The translations by half the cell along any set of the axes with an even count (grid steps), zero first."""

    found = []
    for bits in product((0, 1), repeat=3):
        bits = np.asarray(bits, dtype=np.int64)
        if np.any((bits == 1) & (counts % 2 == 1)):
            continue
        found.append(bits * (counts // 2))
    return found


_PROJECTOR_ORBITS_SWITCH = "PARSEC_SECTOR_PROJECTOR_ORBITS"


def sector_projector_orbits_setting() -> str:
    """``PARSEC_SECTOR_PROJECTOR_ORBITS``: ``auto`` (default) gives the sectors of a point-group reduction the
    projectors of one atom per orbit (:func:`compress_projectors_for_sectors`); ``off`` those of every atom, bit
    for bit as before."""

    value = os.environ.get(_PROJECTOR_ORBITS_SWITCH, "auto").strip().lower() or "auto"
    if value not in {"auto", "off"}:
        raise ValueError(f"{_PROJECTOR_ORBITS_SWITCH} must be auto or off, not {value!r}")
    return value


def _atom_orbits(atoms, operations, translations, grid, tolerance: float):
    """``(representatives, sizes)``: the smallest index in the orbit of every atom under the operations
    ``r -> R r + t`` and the number of atoms in it, or ``None`` where an image matches no atom of its species.

    The operations form a group, so the orbit of an atom is the set of its images (the identity among them).
    """

    if not atoms:
        return None
    positions = np.asarray([atom.position for atom in atoms], dtype=np.float64)
    symbols = np.asarray([atom.symbol for atom in atoms])
    period = _lattice_period(grid)
    steps = None
    if translations is not None:
        counts = np.asarray(grid.points_per_axis, dtype=np.float64)
        steps = np.diag(np.asarray(grid.cell.lattice_vectors, dtype=np.float64)) / counts
    radius = 2.0 * (tolerance * (1.0 + 1.0e-9) + 1.0e-12)
    images = np.empty((len(operations), positions.shape[0]), dtype=np.int64)
    for symbol in np.unique(symbols):
        members = np.flatnonzero(symbols == symbol)
        points = positions[members]
        tree = _matching_tree(points, period)
        for g, operation in enumerate(operations):
            image = points @ np.asarray(operation, dtype=np.float64).T
            if translations is not None:
                image = image + np.asarray(translations[g], dtype=np.float64) * steps
            queries = image if period is None else _folded(image, period)
            distances, nearest = tree.query(queries, k=1, distance_upper_bound=radius)
            if not np.all(np.isfinite(distances)):
                return None
            images[g, members] = members[nearest]
    representatives = images.min(axis=0)
    ordered = np.sort(images, axis=0)
    sizes = 1 + np.count_nonzero(np.diff(ordered, axis=0), axis=0)
    return representatives, sizes.astype(np.int64)


def compress_projectors_for_sectors(operator, reduction):
    """The projectors that give every sector of ``reduction`` its nonlocal operator, one atom per orbit.

    For an operation ``h`` of the group that carries atom ``a`` onto ``h a``, the projectors of ``h a`` are those
    of ``a`` moved by ``h`` with their ``2l + 1`` real harmonics turned by ``R_h`` (orthogonal within a channel,
    of one sign ``D_l``), so ``B_ha D B_ha^T = P_h B_a D B_a^T P_h^T``; the sector basis ``U`` of a real
    one-dimensional character satisfies ``U^T P_h = chi(h) U^T``, and ``chi(h)^2 = 1``.  Every atom of an orbit
    therefore gives the sector the same ``U^T B_a D B_a^T U``, and the columns of the representative scaled by
    the square root of the orbit size give their sum: ``1/|orbit|`` of the columns, the same operator up to
    round-off.  ``operator`` unchanged where the reduction knows no orbits, ``PARSEC_SECTOR_PROJECTOR_ORBITS=off``,
    or every atom is its own orbit.  Only for the Hamiltonian of the sectors: the projector gradients of the forces
    keep every atom.
    """

    representatives = getattr(reduction, "atom_representatives", None)
    sizes = getattr(reduction, "atom_orbit_sizes", None)
    if representatives is None or sizes is None or sector_projector_orbits_setting() == "off":
        return operator
    labels = tuple(operator.labels)
    if not labels:
        return operator
    atom_of_column = np.fromiter((int(label[0]) for label in labels), dtype=np.int64, count=len(labels))
    if atom_of_column.max() >= representatives.size or atom_of_column.min() < 0:
        return operator
    keep = representatives[atom_of_column] == atom_of_column
    if np.all(keep):
        return operator
    import scipy.sparse as _sparse

    from parsec_python.V_ion.ionic_potential import NonlocalProjectorOperator

    columns = np.flatnonzero(keep)
    scale = np.sqrt(sizes[atom_of_column[columns]].astype(np.float64))
    projectors = _sparse.csc_matrix(_sparse.csc_matrix(operator.projectors)[:, columns] @ _sparse.diags(scale))
    projectors.sort_indices()
    return NonlocalProjectorOperator(
        projectors=projectors,
        signs=np.asarray(operator.signs, dtype=np.float64)[columns],
        labels=tuple(labels[index] for index in columns),
    )


def detect_point_group_reduction(
    grid: RealSpaceGrid,
    atoms: Sequence[Atom],
    abelian: AxisReflectionReduction,
    *,
    atom_tolerance: float = 1.0e-7,
    lattice_tolerance: float = 1.0e-10,
) -> AxisReflectionReduction:
    """``abelian`` (the reduction of before), or a :class:`PointGroupReduction` where that solves less.

    The full group ``G`` is every signed permutation that maps the atoms (species by species) and the active
    grid (row by row, exactly) onto themselves; :func:`.orbital_groups.orbital_group_plan` chooses ``H`` and
    its sectors.  ``abelian`` is returned unchanged where ``G`` is no group (an atom tolerance that accepts
    two operations and refuses their product), where the plan solves no less than ``abelian`` does
    (``1/|abelian|`` of the rows times states), or under ``PARSEC_ORBITAL_GROUP=abelian``.
    """

    if orbital_group_policy() == "abelian" or not atoms:
        return abelian
    from .orbital_groups import multiplication_table, orbital_group_plan

    table = _RowOrderTable(grid) if _fast_maps_requested() else None
    # A periodic cell: the half-cell translations of a cell that repeats a smaller one, and the operations whose
    # translation is a fraction of the cell where they close into a group, join the point group (the operations
    # r -> R r + t; PARSEC_PERIODIC_TRANSLATIONS=off keeps the point group about the origin alone, half the
    # half-cell translations alone).  Without any translation the operations are those of the point group.
    candidates = shifts = modulus = None
    if (
        _lattice_period(grid) is not None
        and _periodic_row_major(grid)
        and periodic_translation_setting() != "off"
    ):
        for fractional in (True, False):
            found, found_shifts = _space_group_operations(
                grid, atoms, atom_tolerance, lattice_tolerance, fractional=fractional
            )
            if not any(np.any(np.asarray(shift) != 0) for shift in found_shifts):
                candidates = found
                break
            counts = np.asarray(grid.points_per_axis, dtype=np.int64)
            try:
                multiplication_table([_affine_matrix(op, shift) for op, shift in zip(found, found_shifts)], modulus=counts)
            except ValueError:
                # operations with a fraction of the cell that do not close: the half-cell translations alone
                continue
            candidates, shifts, modulus = found, found_shifts, counts
            break
    if candidates is None:
        candidates = _point_group_operations(grid, atoms, atom_tolerance, lattice_tolerance, table)
    elements = (
        candidates
        if shifts is None
        else [_affine_matrix(operation, shift) for operation, shift in zip(candidates, shifts)]
    )

    def shift_of(index: int):
        return None if shifts is None else shifts[index]

    if len(elements) <= abelian.group_order:
        return abelian
    try:
        multiplication_table(elements, modulus=modulus)
    except ValueError:
        return abelian
    # the pure translations, in every candidate subgroup (orbital_group_plan, ``required``)
    required = (
        ()
        if shifts is None
        else tuple(
            index for index, operation in enumerate(candidates) if np.array_equal(operation, np.eye(3))
        )
    )
    plan = orbital_group_plan(elements, modulus=modulus, required=required)
    # Taken where it solves at most half of what the abelian group does (Td, Oh, T, Th: a half to a quarter);
    # a smaller gain (D4h: three quarters) keeps the group of before.
    if not plan.cost <= 0.5 / abelian.group_order + 1.0e-12:
        return abelian
    subgroup = [candidates[index] for index in plan.subgroup]
    mappings = []
    for index in plan.subgroup:
        mapping = _grid_row_mapping_operation(
            grid, candidates[index], lattice_tolerance, table=table, translation=shift_of(index)
        )
        if mapping is None:
            return abelian
        mappings.append(mapping)
    representative_rows, full_to_wedge, multiplicities = _orbit_labels(mappings)
    if np.any(multiplicities <= 0):
        raise RuntimeError("invalid empty symmetry orbit")
    characters = np.array(
        [[character[index] for index in plan.subgroup] for character in plan.characters], dtype=np.int8
    )
    coset_images = np.empty((len(plan.cosets), representative_rows.size), dtype=np.int64)
    for c, index in enumerate(plan.cosets):
        # The whole map: with those of H it shows that every operation of G maps the active grid onto itself.
        mapping = _grid_row_mapping_operation(
            grid, candidates[index], lattice_tolerance, table=table, translation=shift_of(index)
        )
        if mapping is None:
            return abelian
        coset_images[c] = full_to_wedge[mapping[representative_rows]]
    order = len(subgroup)
    translation_fields = (
        {}
        if shifts is None
        else {
            "translations": np.ascontiguousarray([shifts[index] for index in plan.subgroup], dtype=np.int64),
            "full_translations": np.ascontiguousarray(shifts, dtype=np.int64),
            "coset_translations": np.ascontiguousarray([shifts[index] for index in plan.cosets], dtype=np.int64),
        }
    )
    orbits = _atom_orbits(
        atoms, subgroup, None if shifts is None else [shifts[index] for index in plan.subgroup], grid, atom_tolerance
    )
    if orbits is not None:
        translation_fields = dict(translation_fields, atom_representatives=orbits[0], atom_orbit_sizes=orbits[1])
    return PointGroupReduction(
        **translation_fields,
        signs=np.ones((order, 3), dtype=np.int8),
        representative_rows=np.ascontiguousarray(representative_rows, dtype=np.int64),
        full_to_wedge=np.ascontiguousarray(full_to_wedge, dtype=np.int64),
        multiplicities=np.ascontiguousarray(multiplicities, dtype=np.int64),
        operations=np.ascontiguousarray(subgroup, dtype=np.int8),
        generator_bits=np.zeros((order, 0), dtype=np.int8),
        full_operations=np.ascontiguousarray(candidates, dtype=np.int8),
        sector_characters=np.ascontiguousarray(characters),
        sector_weights=np.asarray(plan.weights, dtype=np.int64),
        coset_images=np.ascontiguousarray(coset_images),
        coset_operations=np.ascontiguousarray([candidates[index] for index in plan.cosets], dtype=np.int8),
        grid=grid,
    )


def diagonal_subgroup_reduction(
    grid: RealSpaceGrid,
    operations: np.ndarray,
    *,
    lattice_tolerance: float = 1.0e-10,
) -> AxisReflectionReduction | None:
    """The axis-reflection reduction of the diagonal operations among ``operations``.

    ``operations`` are the signed permutation matrices of a group that maps
    the grid onto itself (``SignedPermutationReduction.operations``, the
    group of the orbitals and of the SCF fields).  Its diagonal members
    (sign changes of the axes alone) form a subgroup, so every field on the
    wedge of the group is invariant under them, and the kernels of an
    axis-reflection wedge apply to it.  The signs are taken in the order of
    :meth:`AxisReflectionReduction.detect`, which gives the same orbits for
    the same signs.  ``None`` where the identity is the only diagonal member.
    """

    matrices = np.asarray(operations, dtype=np.int64).reshape(-1, 3, 3)
    diagonal = {
        tuple(int(value) for value in np.diag(matrix))
        for matrix in matrices
        if not np.any(matrix - np.diag(np.diag(matrix)))
    }
    ordered = [
        np.asarray(values, dtype=np.int8)
        for values in product((-1, 1), repeat=3)
        if values in diagonal
    ]
    if len(ordered) <= 1:
        return None
    table = _RowOrderTable(grid) if _fast_maps_requested() else None
    mappings = []
    for signs in ordered:
        mapping = _grid_row_mapping(grid, signs, lattice_tolerance, table)
        if mapping is None:
            raise RuntimeError(f"the diagonal operation {signs.tolist()} does not map the grid")
        mappings.append(mapping)
    representative_rows, full_to_wedge, multiplicities = _orbit_labels(mappings)
    return AxisReflectionReduction(
        signs=np.ascontiguousarray(np.vstack(ordered), dtype=np.int8),
        representative_rows=np.ascontiguousarray(representative_rows, dtype=np.int64),
        full_to_wedge=np.ascontiguousarray(full_to_wedge, dtype=np.int64),
        multiplicities=np.ascontiguousarray(multiplicities, dtype=np.int64),
    )


